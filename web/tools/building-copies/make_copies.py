"""Smaller copies of the Modern building pictures for the Low and Medium Quality (beta 9).

Reads tools/building-copies/art-uses.json (from list-art.ts: every Modern building picture the yard
asks for and how it is cut) and writes, beside each `name@2x.ext` under server/public/:
  - `name@1x.ext`, half the size a side (Low): every picture;
  - `name@1.5x.ext`, three quarters a side (Medium): every picture whose cells are a whole number of
    pixels at 1.5x (an even width and height in game units), or that is drawn whole.
Strips are shrunk cell by cell, so no cell takes colour from its neighbour, with premultiplied alpha
(no dark fringes). Pixi reads the size from the `@1x` / `@1.5x` in the name, so every cell keeps its
place and size in game units. `buildingArtCopies.ts` in the client picks the copy.

Run from web/:  python3 tools/building-copies/make_copies.py
"""
import json
import sys
from multiprocessing import Pool
from pathlib import Path

from PIL import Image

WEB = Path(__file__).resolve().parents[2]
PUBLIC = WEB.parent / "server" / "public"
USES = Path(__file__).with_name("art-uses.json")
DATA = WEB / "src" / "game" / "yard" / "buildingArtCopiesData.ts"


def shrink(im, size):
    return im.convert("RGBa").resize(size, Image.LANCZOS).convert("RGBA")


def grid_of(use):
    """The one cell size (w, h) a file is cut into, or None for a picture drawn whole."""
    cells = {(s["w"], s["h"]) for s in use["strips"]} | {(f["w"], f["h"]) for f in use["frames"]}
    if not cells:
        return None
    if len(cells) > 1 or use["whole"]:
        raise SystemExit(f"cut two ways: {cells} whole={use['whole']}")
    return next(iter(cells))


def medium_ok(use):
    cell = grid_of(use)
    return cell is None or (cell[0] % 2 == 0 and cell[1] % 2 == 0)


def copy(src, scale, cell):
    """`src` (a @2x picture) at `scale` (1 or 1.5 game px per unit)."""
    w2, h2 = src.size
    k = scale / 2
    out_size = (max(1, round(w2 * k)), max(1, round(h2 * k)))
    if cell is None:
        return shrink(src, out_size)
    cw, ch = cell
    cols, rows = w2 // (2 * cw), h2 // (2 * ch)
    ow, oh = round(cw * scale), round(ch * scale)
    assert ow == cw * scale and oh == ch * scale, (cell, scale)
    out = Image.new("RGBA", (max(out_size[0], cols * ow), max(out_size[1], rows * oh)), (0, 0, 0, 0))
    for r in range(rows):
        for c in range(cols):
            box = (c * 2 * cw, r * 2 * ch, (c + 1) * 2 * cw, (r + 1) * 2 * ch)
            out.paste(shrink(src.crop(box), (ow, oh)), (c * ow, r * oh))
    return out


def save(im, path):
    if path.suffix == ".webp":
        im.save(path, "WEBP", quality=85, alpha_quality=100, method=6)
    else:
        im.save(path, "PNG", optimize=True)


def one(item):
    rel, use = item
    src_path = PUBLIC / rel
    src = Image.open(src_path).convert("RGBA")
    cell = grid_of(use)
    save(copy(src, 1, cell), src_path.with_name(src_path.name.replace("@2x.", "@1x.")))
    if medium_ok(use):
        save(copy(src, 1.5, cell), src_path.with_name(src_path.name.replace("@2x.", "@1.5x.")))
    return rel


def main():
    uses = json.loads(USES.read_text())
    only = set(sys.argv[1:])
    todo = [item for item in uses.items() if not only or item[0] in only]
    with Pool(8) as pool:
        made = len(pool.map(one, todo))
    print(f"{made} pictures copied")
    write_data(uses)


def write_data(uses):
    """The client's list: each picture with copies, 2 with a `@1.5x` as well as a `@1x`, 1 with only the `@1x`."""
    rows = "".join(
        f'  "{rel[len("assets/buildings/"):]}": {2 if medium_ok(use) else 1},\n' for rel, use in sorted(uses.items())
    )
    DATA.write_text(
        "// Generated by web/tools/building-copies/make_copies.py from art-uses.json; do not edit.\n"
        "/**\n"
        " * The Modern building pictures (paths under `/assets/buildings/`) that have smaller copies beside\n"
        " * their `@2x` (beta 9, `buildingArtCopies.ts`): 2 a `@1.5x` and a `@1x`, 1 only a `@1x` (its cells\n"
        " * are an odd number of game units, so a `@1.5x` cell would not be whole pixels).\n"
        " */\n"
        "export const BUILDING_ART_COPIES: Readonly<Record<string, 1 | 2>> = {\n" + rows + "};\n"
    )


if __name__ == "__main__":
    main()
