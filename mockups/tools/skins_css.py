def block(skin):
    a = f"../assets/{skin}"
    kit = json.load(open(f"{M}/assets/{skin}/kit.json"))
    fr = json.load(open(f"{M}/assets/{skin}/frame.json"))
    s = SKINS[skin]
    out = [f'[data-skin="{skin}"] {{']
    out.append(f'  --frame: url("{a}/frame@2x.png"); --frame-slice: {fr["slice"]}; --frame-w: {fr["slice"] / 2}px;')
    for k, v in s["vars"].items():
        out.append(f"  {k}: {v};")
    out.append("}")
    for piece, (cl, cr) in s["caps"].items():
        w, h = kit[piece]
        out.append(f'[data-skin="{skin}"] .k-{piece} {{ --img: url("{a}/{piece}@2x.png"); --ah: {h}; --cl: {round(cl * h)}; --cr: {round(cr * h)}; }}')
    w, h = kit["close"]
    out.append(f'[data-skin="{skin}"] .k-close {{ background-image: url("{a}/close@2x.png"); aspect-ratio: {w} / {h}; }}')
    return "\n".join(out)


