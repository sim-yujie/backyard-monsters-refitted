  "production",
  "loot",
  "raidersCarry",
  "takeoverCost",
  "enemyTakeoverCost",
  "kitCost",
  "outpostHatchCost",
  "fortifyCost",
  "buildingHealth",
  "outpostHealth",
  "towerDamage",
  "trapDamage",
